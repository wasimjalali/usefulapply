import { dispatchScheduled } from './cron';
import { BRAND } from './lib/brand';

// Minimal shape of the Workers ExecutionContext. Full runtime types are not
// generated because they clash with Next's DOM lib.
type ExecutionContext = {
  waitUntil(promise: Promise<unknown>): void;
  passThroughOnException(): void;
};

// Minimal shape of a Workers Queue batch (same reason as ExecutionContext above).
type QueueBatch = {
  queue: string;
  messages: ReadonlyArray<{
    id?: string;
    body: unknown;
    attempts: number;
    ack(): void;
    retry(options?: { delaySeconds?: number }): void;
  }>;
};

// Generated by `opennextjs-cloudflare build`. Wrangler bundles this file
// as the Worker entry so we can add scheduled() next to OpenNext's fetch.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- the file only exists after opennextjs-cloudflare build
// @ts-ignore generated by opennextjs-cloudflare build, absent on a fresh checkout
import nextApp from '../.open-next/worker.js';
// OpenNext's Durable Object classes must stay exported from the entry even when
// the current config doesn't use them, or a future queue/tag-cache config fails to deploy.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- same generated file
// @ts-ignore generated by opennextjs-cloudflare build, absent on a fresh checkout
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from '../.open-next/worker.js';
// Cron handlers call getCloudflareContext (D1 + EMAIL). That store is ALS
// set by OpenNext's fetch wrapper, so scheduled() must enter the same ALS.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- same generated file
// @ts-ignore generated by opennextjs-cloudflare build, absent on a fresh checkout
import { runWithCloudflareRequestContext } from '../.open-next/cloudflare/init.js';

const worker = {
  fetch(request: Request, env: CloudflareEnv, ctx: ExecutionContext) {
    const url = new URL(request.url);
    if (url.hostname === 'admin.usefulapply.com' && url.pathname === '/') {
      return Response.redirect(`${url.origin}/admin-dashboard`, 308);
    }
    // Product: /features is a 301 to `/`. Next `permanent: true` is 308 and
    // previously hashed to /#what-you-get, which crawlers drop. Handle it at
    // the Worker edge so Location is `/` with no fragment.
    if (url.pathname === '/features' || url.pathname === '/features/') {
      return Response.redirect(`${url.origin}/`, 301);
    }
    return nextApp.fetch(request, env, ctx);
  },
  async scheduled(controller: { cron: string }, env: CloudflareEnv, ctx: ExecutionContext) {
    // OpenNext derives its origin from the first request an isolate sees, so
    // this must be the real site origin, not a literal that can drift.
    const origin = (env as { NEXT_PUBLIC_SITE_URL?: string }).NEXT_PUBLIC_SITE_URL || BRAND.url;
    const request = new Request(`${origin.replace(/\/$/, '')}/__scheduled`);
    await runWithCloudflareRequestContext(request, env, ctx, async () => {
      try {
        await dispatchScheduled(controller.cron);
      } catch (error) {
        // Surface the failure in Workers Logs and rethrow so the run is marked failed.
        console.error(`[cron] ${controller.cron} failed:`, error instanceof Error ? error.message : error);
        throw error;
      }
    });
  },
  // Queue consumer for `agent-generation` and its dead-letter queue. Like
  // scheduled(), it must enter OpenNext's request context so getDb() and the
  // other bindings resolve.
  async queue(batch: QueueBatch, env: CloudflareEnv, ctx: ExecutionContext) {
    const origin = (env as { NEXT_PUBLIC_SITE_URL?: string }).NEXT_PUBLIC_SITE_URL || BRAND.url;
    const request = new Request(`${origin.replace(/\/$/, '')}/__queue`);
    await runWithCloudflareRequestContext(request, env, ctx, async () => {
      const { handleAgentQueueBatch } = await import('./lib/services/generation-runner');
      await handleAgentQueueBatch(batch);
    });
  },
};

export default worker;
