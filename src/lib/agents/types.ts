/**
 * Agent Types and Interfaces
 * Karko AI Unified Agent Architecture
 */

// Token usage tracking for API calls
export interface TokenUsage {
  input: number;
  output: number;
}

// Agent role (unified agent handles all tasks)
export type AgentRole = 
  | 'karko_ai'
  | 'unified'
  | 'context'
  | 'writer';

export type AgentStatus = 
  | 'idle'
  | 'thinking'
  | 'executing'
  | 'waiting'
  | 'completed'
  | 'error';

/**
 * MasterContext - The single source of truth for the entire workflow
 * Karko AI builds and consumes this context for document generation
 */
export interface MasterContext {
  sessionId: string;

  // Raw inputs
  jobDescription: string;
  rawCV: string;
  masterCV?: string;
  
  // Language detection (auto-detected or user override)
  detectedLanguage?: 'en' | 'de';
  userLanguageOverride?: 'en' | 'de';

  // Applicant profile (extracted from CV by Context Agent)
  applicant?: {
    name: string;
    email: string;
    phone?: string;
    address?: string;
    headline?: string;
    skills: string[];
    tools: string[];
    languages: string[];
    experiences: Array<{
      company: string;
      title: string;
      startDate?: string;
      endDate?: string;
      bullets: string[];
    }>;
    certifications: string[];
  };

  // Job details (parsed from JD by Context Agent)
  job?: {
    title: string;
    companyName: string;
    location?: string;
    workType?: string;
    requiredSkills: string[];
    niceToHaveSkills: string[];
    responsibilities: string[];
    startDate?: string;
    expectedSalary?: string;
  };

  // Company research (from Tavily/GPT search)
  companyResearch?: {
    name: string;
    address?: string;
    website?: string;
    description?: string;
    values?: string[];
    culture?: string[];
    techStack?: string[];
    recentNews?: string[];
  };

  // Match analysis (computed by Context Agent)
  match?: {
    score: number;
    matchingSkills: string[];
    missingSkills: string[];
  };

  // Final outputs (generated by Writer Agent)
  // Solution B: Structured JSON output - AI writes CVData directly, no parsing needed
  optimizedCV?: {
    content: string;  // Legacy: plain text CV (kept for backward compatibility)
    changes: Array<{
      section: string;
      before: string;
      after: string;
      reason: string;
    }>;
  };
  // NEW: Structured CV data - AI outputs this directly, template renders it
  optimizedCVData?: {
    personal: {
      fullName: string;
      email: string;
      phone?: string;
      currentTitle?: string;
      address?: string;
      city?: string;
      country?: string;
      linkedIn?: string;
      website?: string;
      github?: string;
    };
    summary?: string;
    experience: Array<{
      id: string;
      company: string;
      position: string;
      location?: string;
      startDate: string;
      endDate?: string;
      current?: boolean;
      bullets: string[];
      technologies?: string[];
    }>;
    education: Array<{
      id: string;
      institution: string;
      degree: string;
      field?: string;
      location?: string;
      startDate?: string;
      endDate?: string;
      grade?: string;
      highlights?: string[];
    }>;
    skills: Array<{
      category: string;
      items: string[];
    }>;
    languages: Array<{
      language: string;
      proficiency: string;
    }>;
    certifications: Array<{
      id: string;
      name: string;
      issuer: string;
      date?: string;
    }>;
    // NEW: Optimization analysis for "Changes" tab
    analysis?: OptimizationAnalysis;
  };
  coverLetter?: string;
  applicationEmail?: { subject: string; body: string };

  metadata?: Record<string, unknown>;
}

/**
 * OptimizationAnalysis - Data for the "Changes" tab
 * AI must populate this to explain what optimizations were made
 */
export interface OptimizationAnalysis {
  summary: string;                   // 2-sentence strategy summary
  key_changes: string[];             // List of specific changes made
  ats_compatibility: number;         // Estimated ATS score 0-100
  missing_keywords_added: string[];  // Keywords added for ATS
}

// Event types for streaming progress
export type AgentEvent = 
  | { type: 'step_started'; step: { id: string; description: string } }
  | { type: 'step_completed'; step: { id: string; description?: string }; tokens?: { input: number; output: number } }
  | { type: 'step_error'; step: { id: string }; error: string }
  | { type: 'message'; content: string }
  | { type: 'progress'; percent: number; message: string }
  | { type: 'tool_usage'; tool: string; output: unknown; display?: boolean };

export type AgentEventHandler = (event: AgentEvent) => void;

export interface AgentResult<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
  usage?: {
    inputTokens: number;
    outputTokens: number;
    cost: number;
  };
  latencyMs: number;
}

