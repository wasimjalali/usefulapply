/**
 * Agent Types and Interfaces
 * 3-Agent Architecture: Orchestrator → Context Agent → Writer Agent
 */

// Simplified agent roles for 3-agent architecture
export type AgentRole = 
  | 'orchestrator'
  | 'context'
  | 'writer';

export type AgentStatus = 
  | 'idle'
  | 'thinking'
  | 'executing'
  | 'waiting'
  | 'completed'
  | 'error';

/**
 * MasterContext - The single source of truth for the entire workflow
 * Context Agent populates this, Writer Agent consumes it
 */
export interface MasterContext {
  sessionId: string;

  // Raw inputs
  jobDescription: string;
  rawCV: string;
  masterCV?: string;

  // Applicant profile (extracted from CV by Context Agent)
  applicant?: {
    name: string;
    email: string;
    phone?: string;
    address?: string;
    headline?: string;
    skills: string[];
    tools: string[];
    languages: string[];
    experiences: Array<{
      company: string;
      title: string;
      startDate?: string;
      endDate?: string;
      bullets: string[];
    }>;
    certifications: string[];
  };

  // Job details (parsed from JD by Context Agent)
  job?: {
    title: string;
    companyName: string;
    location?: string;
    workType?: string;
    requiredSkills: string[];
    niceToHaveSkills: string[];
    responsibilities: string[];
    startDate?: string;
    expectedSalary?: string;
  };

  // Company research (from Tavily/GPT search)
  companyResearch?: {
    name: string;
    address?: string;
    website?: string;
    description?: string;
    values?: string[];
    culture?: string[];
    techStack?: string[];
    recentNews?: string[];
  };

  // Match analysis (computed by Context Agent)
  match?: {
    score: number;
    matchingSkills: string[];
    missingSkills: string[];
  };

  // Final outputs (generated by Writer Agent)
  optimizedCV?: {
    content: string;
    changes: Array<{
      section: string;
      before: string;
      after: string;
      reason: string;
    }>;
  };
  coverLetter?: string;
  applicationEmail?: { subject: string; body: string };

  metadata?: Record<string, unknown>;
}

// Event types for streaming progress
export type AgentEvent = 
  | { type: 'step_started'; step: { id: string; description: string } }
  | { type: 'step_completed'; step: { id: string; description?: string } }
  | { type: 'step_error'; step: { id: string }; error: string }
  | { type: 'message'; content: string }
  | { type: 'progress'; percent: number; message: string }
  | { type: 'tool_usage'; tool: string; output: unknown; display?: boolean };

export type AgentEventHandler = (event: AgentEvent) => void;

export interface AgentResult<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
  usage?: {
    inputTokens: number;
    outputTokens: number;
    cost: number;
  };
  latencyMs: number;
}

// Legacy types kept for backward compatibility during migration
export interface AgentStep {
  id: string;
  name: string;
  description: string;
  agent: AgentRole;
  status: AgentStatus;
}

export interface AgentConfig {
  maxRetries: number;
  timeoutMs: number;
}

export const DEFAULT_AGENT_CONFIG: AgentConfig = {
  maxRetries: 3,
  timeoutMs: 60000,
};
