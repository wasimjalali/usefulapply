/**
 * OptimizationAnalysis - Data for the "Changes" tab
 * AI must populate this to explain what optimizations were made
 */
export interface OptimizationAnalysis {
  summary: string;                   // 2-sentence strategy summary
  key_changes: string[];             // List of specific changes made
  ats_compatibility: number;         // Estimated ATS score 0-100
  missing_keywords_added: string[];  // Keywords added for ATS
}

// Event types for streaming progress
export type AgentEvent = 
  | { type: 'step_started'; step: { id: string; description: string } }
  | { type: 'step_completed'; step: { id: string; description?: string }; tokens?: TokenUsage; latencyMs?: number }
  | { type: 'step_error'; step: { id: string }; error: string }
  | { type: 'message'; content: string }
  | { type: 'progress'; percent: number; message: string }
  | { type: 'tool_usage'; tool: string; output: unknown; display?: boolean };

export type AgentEventHandler = (event: AgentEvent) => void;

/** The four documents a kit run writes. Each one succeeds or fails on its own. */
export type KitDocument = 'cv' | 'coverLetter' | 'applicationEmail' | 'followUpEmail';

export const KIT_DOCUMENTS: readonly KitDocument[] = ['cv', 'coverLetter', 'applicationEmail', 'followUpEmail'];

/**
 * Why a kit document is missing. VALIDATION_FAILED: the model answered but the
 * answer failed a quality check after its one retry. GENERATION_FAILED: any
 * other error (provider, parse, grounding). Codes only, never model output.
 */
export type KitDocumentErrorCode = 'VALIDATION_FAILED' | 'GENERATION_FAILED';

/** Only the documents that failed are present. An empty object is a whole kit. */
export type KitDocumentErrors = Partial<Record<KitDocument, KitDocumentErrorCode>>;

export interface AgentResult<T = unknown> {
  success: boolean;
  data?: T;
  error?: string;
  usage?: {
    inputTokens: number;
    outputTokens: number;
    cost: number;
  };
  latencyMs: number;
}
